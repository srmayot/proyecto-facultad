    private void recalcularTotales() {
        double totalGeneral = 0.0;
        double totalIva10 = 0.0;
        double totalIva5 = 0.0;

        for (int i = 0; i < tblDetalle.getRowCount(); i++) {
            // Obtenemos el subtotal como Double (asumiendo que está en la columna 5)
            double subtotal = (Double) tblDetalle.getValueAt(i, 5);

            // Obtenemos el tipo de IVA como String (asumiendo que está en la columna 4: "10%", "5%" o "Exenta")
            String ivaTipo = (String) tblDetalle.getValueAt(i, 4);

            totalGeneral += subtotal;

            if (ivaTipo.equals("10%")) {
                totalIva10 += (subtotal / 11);
            } else if (ivaTipo.equals("5%")) {
                totalIva5 += (subtotal / 21);
            }
            // Si es "Exenta", no suma IVA, solo al total general.
        }

        double totalIvaGeneral = totalIva10 + totalIva5;

        // Asignamos los valores formateados a tus etiquetas del pie de factura (pnlPie)
        lblTotalGeneral.setText("Gs. " + String.format("%,.0f", totalGeneral));
        lblTotal10.setText("Gs. " + String.format("%,.0f", totalIva10));
        lblTotal5.setText("Gs. " + String.format("%,.0f", totalIva5));
        lblTotalIva.setText("Gs. " + String.format("%,.0f", totalIvaGeneral));
    }

