    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
// 🛑 1. Validación exigida por Moodle: Verificar cliente y grilla vacía
        if (txtRucCliente.getText().trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "No se puede facturar sin un cliente asignado.", "Error de validación", javax.swing.JOptionPane.ERROR_MESSAGE);
            return; // Detiene el guardado
        }

        javax.swing.table.DefaultTableModel modeloValidacion = (javax.swing.table.DefaultTableModel) tblDetalle.getModel();
        if (modeloValidacion.getRowCount() == 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "La grilla de la factura está vacía. Debe agregar al menos un ítem.", "Error de validación", javax.swing.JOptionPane.ERROR_MESSAGE);
            return; // Detiene el guardado
        }

        // 2. Lógica principal de Base de Datos y Transacción ACID
        java.sql.Connection conn = null;
        try {
            conn = DBConnection.getInstance().getConnection();

            // Desactivamos el auto-commit
            conn.setAutoCommit(false);

            String sqlCabecera = "INSERT INTO facturas (nro_factura, ruc_cliente, fecha, total_general) VALUES (?, ?, ?, ?)";
            java.sql.PreparedStatement psCabecera = conn.prepareStatement(sqlCabecera, java.sql.Statement.RETURN_GENERATED_KEYS);

            // Asignación de datos desde los campos visuales de la cabecera:
            String nroFactura = txtNroFactura.getText();
            String rucCliente = txtRucCliente.getText();

            psCabecera.setString(1, nroFactura);
            psCabecera.setString(2, rucCliente);
            psCabecera.setDate(3, java.sql.Date.valueOf(java.time.LocalDate.now()));

            // Extraemos el total general quitando el texto "Gs. " para dejar solo el número decimal
            double totalGen = Double.parseDouble(lblTotalGeneral.getText().replace("Gs. ", "").replace(".", "").replace(",", "."));
            psCabecera.setDouble(4, totalGen);

            psCabecera.executeUpdate();

            // Obtenemos el ID autoincrementable generado para la cabecera
            java.sql.ResultSet rsKeys = psCabecera.getGeneratedKeys();
            int idCabecera = 0;
            if (rsKeys.next()) {
                idCabecera = rsKeys.getInt(1);
            }

            // Insertar los Detalles en bucle recorriendo la tabla (tblDetalle)
            javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) tblDetalle.getModel();

            for (int i = 0; i < modelo.getRowCount(); i++) {
                String sqlDetalle = "INSERT INTO detalle_facturas (id_factura, codigo_producto, cantidad, precio_unitario, subtotal, iva_tipo) VALUES (?, ?, ?, ?, ?, ?)";
                java.sql.PreparedStatement psDetalle = conn.prepareStatement(sqlDetalle);

                String codigoProd = (String) modelo.getValueAt(i, 0);
                int cantidad = (Integer) modelo.getValueAt(i, 2);
                double precioUnit = (Double) modelo.getValueAt(i, 3);
                String ivaTipo = (String) modelo.getValueAt(i, 4);
                double subtotal = (Double) modelo.getValueAt(i, 5);

                psDetalle.setInt(1, idCabecera);
                psDetalle.setString(2, codigoProd);
                psDetalle.setInt(3, cantidad);
                psDetalle.setDouble(4, precioUnit);
                psDetalle.setDouble(5, subtotal);
                psDetalle.setString(6, ivaTipo);

                psDetalle.executeUpdate();
            }

            // Confirmamos la transacción con commit()
            conn.commit();
            javax.swing.JOptionPane.showMessageDialog(this, "¡Factura registrada y guardada con éxito!");

            // 📄 Generador de PDF comentado temporalmente para evitar errores de red/librería local:
            // generarPdfFactura(nroFactura, rucCliente);
            // limpiarFormulario();
        } catch (java.sql.SQLException e) {
            if (conn != null) {
                try {
                    conn.rollback();
                    System.err.println("Transacción revertida (Rollback ejecutado).");
                } catch (java.sql.SQLException ex) {
                    ex.printStackTrace();
                }
            }
            javax.swing.JOptionPane.showMessageDialog(this, "Error de base de datos al guardar: " + e.getMessage(), "Error ACID", javax.swing.JOptionPane.ERROR_MESSAGE);
        } catch (Exception e) {
            if (conn != null) {
                try {
                    conn.rollback();
                } catch (Exception ex) {
                }
            }
            javax.swing.JOptionPane.showMessageDialog(this, "Error inesperado: " + e.getMessage(), "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        } finally {
            if (conn != null) {
                try {
                    conn.setAutoCommit(true);
                    conn.close();
                } catch (java.sql.SQLException e) {
                    e.printStackTrace();
                }
            }
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

